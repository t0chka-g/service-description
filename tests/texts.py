def attribute(name: str, value: str) -> ExtractedAttribute:
    return ExtractedAttribute(
        name=name,
        value=value,
        source=AttributeSource.SPECS,
        evidence=value,
    )


def manometer_input() -> GenerationInput:
    """Четыре подтвержденные характеристики демонстрационного манометра."""

    return GenerationInput(
        name=MANOMETER_NAME,
        manufacturer=MANUFACTURER,
        attributes=[attribute(name, value) for name, value in MANOMETER_SPECS.items()],
    )


def manometer_description() -> str:
    """Естественное описание, попадающее в целевой диапазон 900–1050."""

    return " ".join(MANOMETER_SENTENCES)


def with_length(core: str, length: int) -> str:
    """Дополнить текст разными нейтральными фразами до точной длины.

    Последняя фраза — перечень различных слов, обрезанный до нужной длины,
    поэтому ни одно предложение не повторяется.
    """

    if len(core) >= length:
        raise AssertionError(f"core is {len(core)}, target {length}")
    text = core
    for sentence in NEUTRAL_SENTENCES:
        if len(text) + 1 + len(sentence) > length - _TAIL_MARGIN:
            continue
        text = f"{text} {sentence}"
    remaining = length - len(text) - 1
    tail = ("Также обратите внимание на " + ", ".join(_TAIL_WORDS))[: remaining - 1]
    while not tail[-1].isalpha():
        tail = tail[:-1] + "а"
    text = f"{text} {tail}."
    assert len(text) == length, (len(text), length)
    return text


def long_text(core: str, length: int) -> str:
    """Текст длиннее лимита: разные предложения, конец каждого — точка."""

    text = core
    extra = list(NEUTRAL_SENTENCES)
    while len(text) < length and extra:
        text = f"{text} {extra.pop(0)}"
    assert len(text) >= length, (len(text), length)
    return text


def full_draft(
    data: GenerationInput,
    description: str | None = None,
    **overrides: Any,
) -> dict[str, Any]:
    """Ответ модели на основной запрос: карточка без служебных полей."""

    title = data.name.strip()[:70].rstrip()
    payload: dict[str, Any] = {
        "seo_title": title,
        "seo_description": description if description is not None else manometer_description(),
        "search_queries": [
            f"{title} купить",
            f"{title} характеристики",
            f"{data.manufacturer} манометр",
        ],
        "commercial_block": (
            f"{title}: {data.attributes[0].name} {data.attributes[0].value}. "
            f"Производитель: {data.manufacturer}."
        ),
    }
    payload.update(overrides)
    return payload


def repair_reply(description: str) -> dict[str, str]:
    """Ответ модели на запрос исправления описания."""

    return {"seo_description": description}
